    private val lineRe = Regex("""FAULT\s+CODES?\s*:\s*(.*)""", RegexOption.IGNORE_CASE)

    /** The codes of a READ reply, upper case: ["84", "12"], empty for "none"; null if [text] is not one */
    fun parse(text: String): List<String>? {
        val codes = text.lines().firstNotNullOfOrNull { lineRe.find(it.trim())?.groupValues?.get(1) } ?: return null
        return codes.split(',', ' ', ';').map { it.trim().uppercase() }
            // 00 and FF: an empty cell of the memory
            .filter { it.isNotEmpty() && it != "NONE" && it != "00" && it != "FF" }
            .map { if (it.length == 1) "0$it" else it }
    }

    fun name(code: String): String? = names[code] ?: code.toIntOrNull(16)?.let {
        when (it) {
            in 0x64..0x7E -> "ошибка производителя авто ${it - 0x5F}"
            in 0xE0..0xFE -> "ошибка производителя авто ${it - 0xE0 + 33}"
            else -> null
        }
    }

    /** "84 — напряжение питания слишком низкое", the code alone if unknown */
    fun describe(code: String) = name(code)?.let { "$code — $it" } ?: code

    /**
     * One code per line; [before]: the codes the previous READ got, null if none was read: then
     * the ones not among them are marked new (READ does not erase, the old ones stay in the memory)
     */
    fun text(codes: List<String>, before: List<String>?): String =
        if (codes.isEmpty()) "нет"
        else codes.joinToString("\n") { describe(it) + if (before != null && it !in before) " (новая)" else "" }

    fun join(codes: List<String>) = codes.joinToString(", ")
    fun split(s: String) = s.split(", ").filter { it.isNotEmpty() }
}
